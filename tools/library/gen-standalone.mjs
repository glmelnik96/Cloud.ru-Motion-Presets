#!/usr/bin/env node
// Compiles both library schemas into one ES module for the panel, panel/src/generated/catalog-validate.mjs
// (plan 2026-10-05 P8): Ajv standalone code with the options of validate.mjs, exporting validateCatalogSchema and
// validateSourceSchema. The panel cannot read the schemas with fs, and compiling them at run time would ship all
// of Ajv. Vite bundles the module with the few Ajv runtime helpers it imports. The file is committed;
// tests/library/gen-standalone.test.mjs fails when it is stale, and tools/panel/build.mjs rewrites a stale copy
// before vite runs, so a panel build always compiles the current schemas (P8).
//   node tools/library/gen-standalone.mjs [--check]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { AJV_OPTIONS, CATALOG_SCHEMA, SRC_SCHEMA } from './validate.mjs';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT = path.join(REPO, 'panel', 'src', 'generated', 'catalog-validate.mjs');

const HEADER = `// Generated by tools/library/gen-standalone.mjs from tools/library/schema/*.json; do not edit.
// Ajv standalone validators (JSON Schema 2020-12) with the options of tools/library/validate.mjs. Use them with
// checkLibrary() from tools/library/rules.mjs, e.g. checkLibrary(doc, 'catalog', validateCatalogSchema).
`;

// TypeScript does not see the errors property Ajv sets inside the validate function, so the exports get a type.
const TYPES = `/**
 * @typedef {{ instancePath: string, schemaPath: string, keyword: string, params: Record<string, any>, message?: string, propertyName?: string }} SchemaError
 * @typedef {((data: unknown) => boolean) & { errors?: SchemaError[] | null }} SchemaValidate
 */`;

// Ajv's standalone code takes its runtime helpers with require() even in ESM mode, and an ES module has no
// require. Each helper becomes a namespace import. They are CommonJS: Node and bundlers in Node mode give
// module.exports as the default export, other loaders give exports.default.
const INTEROP = 'const ajvCjs = (ns) => (ns.default && ns.default.__esModule ? ns.default : ns);';

export function generate() {
  const ajv = new Ajv2020({ ...AJV_OPTIONS, code: { source: true, esm: true, lines: true } });
  ajv.addSchema(SRC_SCHEMA);
  ajv.addSchema(CATALOG_SCHEMA);
  let code = standaloneCode(ajv, { validateCatalogSchema: CATALOG_SCHEMA.$id, validateSourceSchema: SRC_SCHEMA.$id });
  if (/\bajvCjs\b|\bajvRuntime_/.test(code)) throw new Error('generated code already uses ajvCjs or ajvRuntime_');
  const helpers = new Set();
  code = code.replace(/require\("ajv\/dist\/runtime\/([A-Za-z0-9_]+)"\)/g, (_, name) => {
    helpers.add(name);
    return `ajvCjs(ajvRuntime_${name})`;
  });
  if (/\brequire\(/.test(code)) throw new Error('generated code requires something besides the Ajv runtime');
  const imports = [...helpers].sort().map((n) => `import * as ajvRuntime_${n} from 'ajv/dist/runtime/${n}.js';`);
  // Modules are strict anyway.
  const body = code.replace(/^"use strict";\n?/, '').replace(/^export const (validate\w+) = /gm, '/** @type {SchemaValidate} */\n$&');
  return `${HEADER}${imports.join('\n')}\n\n${TYPES}\n\n${INTEROP}\n\n${body.trimEnd()}\n`;
}

// The generated module as committed, with LF (core.autocrlf may check it out with CRLF), or null if it is missing.
export function readGenerated(file = OUT) {
  try {
    return readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    return null;
  }
}

// Writes the module when it is missing or differs from what the generator gives; -> true when it wrote.
export function refresh(file = OUT, code = generate()) {
  if (readGenerated(file) === code) return false;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, code, 'utf8');
  return true;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const code = generate();
  const rel = path.relative(REPO, OUT).replace(/\\/g, '/');
  if (process.argv.includes('--check')) {
    const fresh = readGenerated() === code;
    console.log(fresh ? `fresh ${rel}` : `STALE ${rel}: run node tools/library/gen-standalone.mjs`);
    if (!fresh) process.exitCode = 1;
  } else {
    console.log(`${refresh(OUT, code) ? 'wrote' : 'unchanged'} ${rel}: ${Math.round(code.length / 1024)} KB`);
  }
}
